/*     1895054 : 탭 버튼 이미지      */
jQuery(function($){
	var $obj = $('.img__1895054__');

	$obj.find('> a').on('click', function(){
		var $target = $(this).attr('href');

		$('.medical_tab_btn').removeClass('on');
		$(this).parent().addClass('on');
		$('.medical_tab_cont').hide();
		$('[data-id="'+$target+'"]').show();

		return false;
	});
});

